#include <limits>

#include "rvd/safety.hpp"
#include "test_support.hpp"
using namespace rvd;
Measurement sample() {
  Measurement m;
  m.rail_pos = {10, 0, 0};
  m.t_acquired = .99;
  m.t_received = 1;
  m.frame_id = 2;
  m.synchronization = Synchronization::Synchronized;
  m.timestamp_uncertainty_s = 0;
  return m;
}
int main() {
  RailConfig c;
  ClockOffset clock;
  rejects([&] { clock.to_framework(1); });
  clock.update(1000, 1, .001);
  CHECK(near(clock.to_framework(1001), 2));
  CHECK(clock.status == Synchronization::Estimated && clock.uncertainty_s == .001);
  rejects([&] { clock.update(kNoStamp, 1, .001); });
  CHECK(!deadline_missed(1, 1) && deadline_missed(1.01, 1) && deadline_missed(kNoStamp, 1));
  auto old = sample();
  old.t_acquired = -.01;
  old.frame_id = 1;
  auto m = sample();
  CHECK(validate_timestamps(m, &old, 1, 1, c).empty());
  m.t_acquired = .7;
  CHECK(validate_timestamps(m, nullptr, 1, 1, c) == "STALE_MEASUREMENT");
  m = sample();
  m.frame_id = 1;
  CHECK(validate_timestamps(m, &old, 1, 1, c) == "SENSOR_FROZEN");
  m = sample();
  m.frame_id = 0;
  CHECK(validate_timestamps(m, &old, 1, 1, c) == "OUT_OF_ORDER_MEASUREMENT");
  m = sample();
  m.t_acquired = -.02;
  CHECK(validate_timestamps(m, &old, 1, 1, c) == "OUT_OF_ORDER_MEASUREMENT");
  m = sample();
  m.t_acquired = 1.01;
  CHECK(validate_timestamps(m, nullptr, 1, 1, c) == "STAMP_IN_FUTURE");
  m = sample();
  m.t_acquired = m.t_received = 1.4;
  CHECK(validate_timestamps(m, nullptr, 1, 1.4, c) == "MEASUREMENT_LATE");
  m = sample();
  m.t_acquired = kNoStamp;
  CHECK(validate_timestamps(m, nullptr, 1, 1, c).empty());
  m.t_received = kNoStamp;
  CHECK(validate_timestamps(m, nullptr, 1, 1, c) == "MISSING_TIMESTAMP");
  m = sample();
  m.synchronization = Synchronization::Unknown;
  CHECK(validate_timestamps(m, nullptr, 1, 1, c) == "UNSYNCHRONIZED_TIMESTAMP");
  m = sample();
  m.timestamp_uncertainty_s = .01;
  CHECK(validate_timestamps(m, nullptr, 1, 1, c) == "TIMESTAMP_UNCERTAINTY");
  m = sample();
  CHECK(validate_timestamps(m, nullptr, 1, 1.4, c) == "COMMUNICATION_TIMEOUT");
  auto ready = [&] {
    SafetySupervisor s(c);
    s.transition(RuntimeState::Ready);
    s.transition(RuntimeState::Running);
    return s;
  };
  auto s = ready();
  s.transition(RuntimeState::Hold);
  s.transition(RuntimeState::Ready);
  s.transition(RuntimeState::Running);
  rejects([&] { s.transition(RuntimeState::Initializing); });
  CHECK(!s.measurement(sample(), nullptr, 1, 1, nullptr, true));
  CHECK(s.reason() == "STOP_REQUESTED");
  s.fault("later");
  CHECK(s.reason() == "STOP_REQUESTED");
  rejects([&] { s.transition(RuntimeState::Ready); });
  s.transition(RuntimeState::Stopped);
  s = ready();
  m = sample();
  m.rail_pos[0] = kNoStamp;
  CHECK(!s.measurement(m, nullptr, 1, 1, nullptr));
  CHECK(s.reason() == "INVALID_MEASUREMENT");
  s = ready();
  m = sample();
  m.rail_pos[0] = 21;
  CHECK(!s.measurement(m, nullptr, 1, 1, nullptr));
  CHECK(s.reason() == "MEASURED_RAIL_ENVELOPE");
  s = ready();
  pfcr::Vec3 target{10.1, 0, 0};
  CHECK(!s.measurement(sample(), nullptr, 1, 1, &target));
  CHECK(s.reason() == "RAIL_TRACKING_ERROR");
  s = ready();
  m = sample();
  m.encoder_pos = {10.02, 0, 0};
  CHECK(s.measurement(m, nullptr, 1, 1, nullptr));
  m.encoder_pos = {10.06, 0, 0};
  CHECK(!s.measurement(m, nullptr, 1, 1, nullptr));
  CHECK(s.reason() == "SENSOR_DISAGREEMENT");
  auto before = old;
  before.encoder_pos = {10, 0, 0};
  before.rail_pos = sample().rail_pos;
  s = ready();
  m = sample();
  m.encoder_pos = {10.0003, 0, 0};
  CHECK(s.measurement(m, &before, 1, 1, nullptr));  // identical pose of a stationary rail
  m.encoder_pos = {10.01, 0, 0};
  CHECK(!s.measurement(m, &before, 1, 1, nullptr));
  CHECK(s.reason() == "MEASUREMENT_REPEATED");
  Command cmd;
  cmd.t_tick = 1;
  cmd.t_arrive = 2;
  cmd.rail_target = {10, 0, 0};
  cmd.rail_velocity = {.1, 0, 0};
  s = ready();
  CHECK(s.command(cmd, {}));
  s = ready();
  cmd.rail_target[0] = 21;
  CHECK(!s.command(cmd, {}));
  CHECK(s.reason() == "RAIL_ENVELOPE");
  cmd.rail_target[0] = 10;
  s = ready();
  cmd.rail_velocity[0] = .51;
  CHECK(!s.command(cmd, {}));
  CHECK(s.reason() == "RAIL_SPEED");
  cmd.rail_velocity[0] = .3;
  s = ready();
  CHECK(!s.command(cmd, {-.3, 0, 0}));
  CHECK(s.reason() == "RAIL_ACCELERATION");
  s = ready();
  cmd.rail_velocity[0] = .1;
  cmd.rail_reference = {21, 0, 0};
  CHECK(!s.command(cmd, {}));
  CHECK(s.reason() == "RAIL_ENVELOPE");
  cmd.rail_reference = {10, 0, 0};
  s = ready();
  CHECK(s.command(cmd, {}));
  s = ready();
  cmd.rail_velocity[0] = kNoStamp;
  CHECK(!s.command(cmd, {}));
  CHECK(s.reason() == "INVALID_COMMAND");
  s = ready();
  CHECK(!s.communication(false, false));
  CHECK(s.reason() == "READ_FAILED");
  s = ready();
  CHECK(!s.communication(false, true));
  CHECK(s.reason() == "SEND_FAILED");
  s = ready();
  CHECK(!s.deadline(2.1, 2));
  CHECK(s.reason() == "CONTROL_OVERRUN");
  s = ready();
  pfcr::StepResult result;
  result.action[0] = std::numeric_limits<float>::infinity();
  CHECK(!s.controller_output(result));
  CHECK(s.reason() == "INVALID_CONTROLLER_OUTPUT");
  s = ready();
  CommandAck ack;
  ack.t_sent = 1;
  CHECK(s.acknowledgment(ack, 1, 2, false));
  CHECK(!s.acknowledgment(ack, 1, 2, true));
  CHECK(s.reason() == "PLC_ACK_TIMEOUT");
  s = ready();
  CHECK(!s.hardware({}, 1));
  CHECK(s.reason() == "HARDWARE_STATUS_UNAVAILABLE");
  s = ready();
  HardwareSafetyStatus hs{true, false, true, true, 1};
  CHECK(s.hardware(hs, 1));
  hs.emergency_stop = true;
  CHECK(!s.hardware(hs, 1));
  CHECK(s.reason() == "STOP_REQUESTED");
}
